// Bundles the in-page agent, and the adapter conformance probe that `motionpr adapter check`
// injects after it, into self-contained IIFEs and exposes them to Node as strings.
// Output: src/agent/agent-bundle.generated.ts (git-ignored). Run via `pnpm generate`.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const cliPkg = JSON.parse(
  await readFile(new URL("../../cli/package.json", import.meta.url), "utf8"),
);

const bundle = async (entry) => {
  const result = await build({
    entryPoints: [`${root}src/agent/${entry}`],
    bundle: true,
    format: "iife",
    platform: "browser",
    // The agent runs in all three engines (Playwright's builds are far newer than these floors).
    target: ["chrome110", "firefox115", "safari16"],
    write: false,
    minify: false,
    legalComments: "none",
    define: { __MOTIONPR_VERSION__: JSON.stringify(cliPkg.version) },
    logLevel: "warning",
  });
  return result.outputFiles[0].text;
};

const source = await bundle("entry.ts");
const probe = await bundle("probe-entry.ts");
const banner = "// Generated by packages/capture/scripts/build-agent.mjs. Do not edit.\n";
await writeFile(
  `${root}src/agent/agent-bundle.generated.ts`,
  `${banner}export const AGENT_SOURCE: string = ${JSON.stringify(source)};\n` +
    `/** The adapter conformance probe (\`motionpr adapter check\` only). */\n` +
    `export const ADAPTER_PROBE_SOURCE: string = ${JSON.stringify(probe)};\n`,
);
console.log(
  `agent bundle: ${(source.length / 1024).toFixed(1)} KB, conformance probe: ${(probe.length / 1024).toFixed(1)} KB`,
);
